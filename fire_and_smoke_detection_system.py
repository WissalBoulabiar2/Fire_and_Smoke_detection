for split in splits:

    # Source directories
    source_images = source_root / split / "images"
    source_labels = source_root / split / "labels"

    # Destination directories
    output_images = output_root / split / "images"
    output_labels = output_root / split / "labels"

    output_images.mkdir(parents=True, exist_ok=True)
    output_labels.mkdir(parents=True, exist_ok=True)

    removed = 0
    corrected = 0
    unchanged = 0

    # --------------------------------------------------------
    # 4.1 COPY IMAGES
    # --------------------------------------------------------

    for image_path in source_images.iterdir():

        if image_path.is_file():

            shutil.copy2(
                image_path,
                output_images / image_path.name
            )

    # --------------------------------------------------------
    # 4.2 CLEAN LABEL FILES
    # --------------------------------------------------------

    for label_path in source_labels.glob("*.txt"):

        # Find corresponding image
        image_path = next(
            (
                p for p in source_images.glob(
                    label_path.stem + ".*"
                )
                if p.is_file()
            ),
            None
        )

        if image_path is None:
            print("Warning: Image not found for", label_path.name)
            continue

        # Read image dimensions
        with Image.open(image_path) as img:
            img_width, img_height = img.size

        cleaned_lines = []

        # Read annotations
        with open(label_path, "r") as f:

            lines = f.readlines()

        for line in lines:

            values = line.strip().split()

            # Check YOLO annotation format
            if len(values) != 5:
                removed += 1
                continue

            try:
                cls, x, y, w, h = map(float, values)
            except ValueError:
                removed += 1
                continue

            # Remove zero-sized boxes
            if w <= 0 or h <= 0:
                removed += 1
                continue

            # ------------------------------------------------
            # Convert normalized YOLO coordinates to pixels
            # ------------------------------------------------

            x1 = (x - w / 2) * img_width
            y1 = (y - h / 2) * img_height

            x2 = (x + w / 2) * img_width
            y2 = (y + h / 2) * img_height

            # ------------------------------------------------
            # Clip bounding boxes to image boundaries
            # ------------------------------------------------

            x1_new = max(0, min(img_width, x1))
            y1_new = max(0, min(img_height, y1))

            x2_new = max(0, min(img_width, x2))
            y2_new = max(0, min(img_height, y2))

            # Remove boxes with no valid intersection
            if x2_new <= x1_new or y2_new <= y1_new:
                removed += 1
                continue

            # ------------------------------------------------
            # Convert coordinates back to YOLO format
            # ------------------------------------------------

            new_x = ((x1_new + x2_new) / 2) / img_width
            new_y = ((y1_new + y2_new) / 2) / img_height

            new_w = (x2_new - x1_new) / img_width
            new_h = (y2_new - y1_new) / img_height

            # Create cleaned annotation
            new_line = (
                f"{int(cls)} "
                f"{new_x:.6f} "
                f"{new_y:.6f} "
                f"{new_w:.6f} "
                f"{new_h:.6f}"
            )

            # Check whether annotation was modified
            if (
                abs(new_x - x) > 1e-6 or
                abs(new_y - y) > 1e-6 or
                abs(new_w - w) > 1e-6 or
                abs(new_h - h) > 1e-6
            ):

                corrected += 1

            else:

                unchanged += 1

            cleaned_lines.append(new_line)

        # Save cleaned annotations
        output_label_path = output_labels / label_path.name

        with open(output_label_path, "w") as f:

            f.write("\n".join(cleaned_lines))

    # --------------------------------------------------------
    # 4.3 DISPLAY SPLIT RESULTS
    # --------------------------------------------------------

    print(f"\n{split.upper()} RESULTS")
    print("--------------------------")
    print("Removed annotations:", removed)
    print("Corrected annotations:", corrected)
    print("Unchanged annotations:", unchanged)

    total_removed += removed
    total_corrected += corrected
    total_unchanged += unchanged


