import cv2
import csv
import numpy as np
from collections import deque
from pathlib import Path
from ultralytics import YOLO

# --------------------------------------------------
# 1. PATHS AND MODEL
# --------------------------------------------------

input_video = "/content/Wildfires 101 _ National Geographic.mp4"
model_path = "/content/runs/fire_smoke/yolo11n_baseline-2/weights/best.pt"

output_dir = Path("/content/runs/fire_smoke/final_system")
output_dir.mkdir(parents=True, exist_ok=True)

output_video = str(output_dir / "fire_smoke_alerts.mp4")
output_csv = str(output_dir / "alert_events.csv")

model = YOLO(model_path)

# --------------------------------------------------
# 2. VIDEO INITIALIZATION
# --------------------------------------------------

cap = cv2.VideoCapture(input_video)

if not cap.isOpened():
    raise RuntimeError("Cannot open input video.")

fps = cap.get(cv2.CAP_PROP_FPS)
width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

fourcc = cv2.VideoWriter_fourcc(*"mp4v")
writer = cv2.VideoWriter(
    output_video, fourcc, fps, (width, height)
)

if not writer.isOpened():
    raise RuntimeError("Cannot create output video.")

# --------------------------------------------------
# 3. TEMPORAL ALERT CONFIGURATION
# --------------------------------------------------

WINDOW_SIZE = 5
MIN_DETECTIONS = 3
CONFIDENCE = 0.25

history = {
    "smoke": deque(maxlen=WINDOW_SIZE),
    "fire": deque(maxlen=WINDOW_SIZE)
}

previous_alerts = {
    "smoke": False,
    "fire": False
}

# --------------------------------------------------
# 4. PROCESS VIDEO FRAME BY FRAME
# --------------------------------------------------

with open(output_csv, "w", newline="") as csvfile:

    csv_writer = csv.writer(csvfile)
    csv_writer.writerow([
        "frame", "timestamp_seconds",
        "alert_type", "max_confidence"
    ])

    frame_number = 0

    while True:
        success, frame = cap.read()

        if not success:
            break

        # YOLO detection
        result = model.predict(
            frame,
            imgsz=640,
            conf=CONFIDENCE,
            iou=0.5,
            device=0,
            verbose=False
        )[0]

        detected = {
            "smoke": False,
            "fire": False
        }

        max_confidence = {
            "smoke": 0.0,
            "fire": 0.0
        }

        if result.boxes is not None:
            for box in result.boxes:
                class_id = int(box.cls[0])
                confidence = float(box.conf[0])

                class_name = model.names[class_id]

                if class_name in detected:
                    detected[class_name] = True
                    max_confidence[class_name] = max(
                        max_confidence[class_name],
                        confidence
                    )

        # Update temporal history
        for hazard in history:
            history[hazard].append(detected[hazard])

        # Confirm alerts
        active_alerts = {}

        for hazard in history:
            active_alerts[hazard] = (
                sum(history[hazard]) >= MIN_DETECTIONS
            )

        # Record new alert events
        timestamp = frame_number / fps if fps > 0 else 0

        for hazard in active_alerts:
            if active_alerts[hazard] and not previous_alerts[hazard]:
                csv_writer.writerow([
                    frame_number,
                    round(timestamp, 2),
                    hazard.upper(),
                    round(max_confidence[hazard], 4)
                ])

            previous_alerts[hazard] = active_alerts[hazard]

        # Draw YOLO bounding boxes
        annotated_frame = result.plot()

        # Alert banner
        if active_alerts["fire"] and active_alerts["smoke"]:
            message = "FIRE + SMOKE ALERT"
            color = (0, 0, 255)

        elif active_alerts["fire"]:
            message = "FIRE ALERT"
            color = (0, 0, 255)

        elif active_alerts["smoke"]:
            message = "SMOKE ALERT"
            color = (0, 165, 255)

        else:
            message = "NO HAZARD DETECTED"
            color = (0, 150, 0)

        cv2.rectangle(
            annotated_frame,
            (0, 0),
            (width, 55),
            color,
            -1
        )

        cv2.putText(
            annotated_frame,
            message,
            (15, 38),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.9,
            (255, 255, 255),
            2
        )

        writer.write(annotated_frame)

        frame_number += 1

        if frame_number % 100 == 0:
            print(
                f"Processed {frame_number}/{total_frames} frames"
            )

cap.release()
writer.release()

print("\nPROCESSING COMPLETE")
print("Output video:", output_video)
print("Alert log:", output_csv)
print("Frames processed:", frame_number)

