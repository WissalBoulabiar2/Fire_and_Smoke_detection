# ============================================================
# 4. CLEAN ALL DATASET SPLITS
# ============================================================

for split in splits:

    source_images = source_root / split / "images"
    source_labels = source_root / split / "labels"

    output_images = output_root / split / "images"
    output_labels = output_root / split / "labels"

    output_images.mkdir(parents=True, exist_ok=True)
    output_labels.mkdir(parents=True, exist_ok=True)

    removed = 0
    corrected = 0
    unchanged = 0

    # Copy images
    for image_path in source_images.iterdir():
        if image_path.is_file():
            shutil.copy2(
                image_path,
                output_images / image_path.name
            )

    # Clean labels
    for label_path in source_labels.glob("*.txt"):

        image_path = next(
            source_images.glob(label_path.stem + ".*"),
            None
        )

        if image_path is None:
            continue

        with Image.open(image_path) as img:
            img_width, img_height = img.size

        cleaned_lines = []

        for line in label_path.read_text().splitlines():

            values = line.split()

            if len(values) != 5:
                removed += 1
                continue

            try:
                cls, x, y, w, h = map(float, values)
            except ValueError:
                removed += 1
                continue

            if (
                not all(map(lambda v: v == v and abs(v) != float("inf"),
                            [cls, x, y, w, h]))
                or cls not in [0, 1]
                or w <= 0 or h <= 0
            ):
                removed += 1
                continue

            # YOLO normalized coordinates -> pixels
            x1 = (x - w / 2) * img_width
            y1 = (y - h / 2) * img_height
            x2 = (x + w / 2) * img_width
            y2 = (y + h / 2) * img_height

            # Clip to image boundaries
            x1n = max(0, min(img_width, x1))
            y1n = max(0, min(img_height, y1))
            x2n = max(0, min(img_width, x2))
            y2n = max(0, min(img_height, y2))

            if x2n <= x1n or y2n <= y1n:
                removed += 1
                continue

            # Convert back to normalized coordinates
            nx = ((x1n + x2n) / 2) / img_width
            ny = ((y1n + y2n) / 2) / img_height
            nw = (x2n - x1n) / img_width
            nh = (y2n - y1n) / img_height

            if any([
                abs(nx - x) > 1e-6,
                abs(ny - y) > 1e-6,
                abs(nw - w) > 1e-6,
                abs(nh - h) > 1e-6
            ]):
                corrected += 1
            else:
                unchanged += 1

            cleaned_lines.append(
                f"{int(cls)} {nx:.6f} {ny:.6f} "
                f"{nw:.6f} {nh:.6f}"
            )

        (output_labels / label_path.name).write_text(
            "\n".join(cleaned_lines)
        )

    total_removed += removed
    total_corrected += corrected
    total_unchanged += unchanged

    print(f"\n{split.upper()}")
    print("Removed:", removed)
    print("Corrected:", corrected)
    print("Unchanged:", unchanged)
    print("Images:", len(list(output_images.iterdir())))
    print("Labels:", len(list(output_labels.glob("*.txt"))))


